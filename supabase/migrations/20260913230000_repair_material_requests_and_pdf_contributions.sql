-- Repair Admin > Yeu cau tai lieu / Dong gop PDF.
-- Preserves existing requests, submitted files and achievement privacy settings.
-- Run this whole file in the project's Supabase SQL Editor. Safe to run again.
begin;

do $$
begin
    if to_regprocedure('public.current_user_is_admin()') is null then
        raise exception 'Missing current_user_is_admin(); configure the existing admin roles first.';
    end if;
    if to_regclass('public.math_categories') is null then
        raise exception 'Missing math_categories; configure the document library first.';
    end if;
end;
$$;

create table if not exists public.math_requests (
    id bigint generated by default as identity primary key,
    name text,
    email text,
    category_id bigint references public.math_categories(id) on delete set null,
    request_text text not null,
    status text not null default 'pending',
    admin_note text,
    reviewed_at timestamptz,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);
alter table public.math_requests add column if not exists admin_note text;
alter table public.math_requests add column if not exists reviewed_at timestamptz;
alter table public.math_requests add column if not exists updated_at timestamptz not null default now();

create table if not exists public.document_contributions (
    id uuid primary key default gen_random_uuid(),
    title text not null,
    description text,
    category_id bigint references public.math_categories(id) on delete set null,
    contributor_name text,
    contributor_email text,
    file_path text not null,
    file_name text not null,
    file_size bigint,
    status text not null default 'pending' check (status in ('pending','approved','rejected')),
    admin_note text,
    reviewed_at timestamptz,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);
alter table public.document_contributions add column if not exists admin_note text;
alter table public.document_contributions add column if not exists reviewed_at timestamptz;
alter table public.document_contributions add column if not exists updated_at timestamptz not null default now();

create index if not exists math_requests_status_created_at_idx on public.math_requests (status, created_at desc);
create index if not exists document_contributions_status_created_at_idx on public.document_contributions (status, created_at desc);
alter table public.math_requests enable row level security;
alter table public.document_contributions enable row level security;

-- Replace policies only on these two moderation queues. Contact details are for admins.
do $$
declare policy_row record; sequence_name text;
begin
    for policy_row in select schemaname, tablename, policyname from pg_policies
        where schemaname = 'public' and tablename in ('math_requests','document_contributions')
    loop
        execute format('drop policy %I on %I.%I', policy_row.policyname, policy_row.schemaname, policy_row.tablename);
    end loop;
    sequence_name := pg_get_serial_sequence('public.math_requests', 'id');
    if sequence_name is not null then
        execute format('grant usage on sequence %s to anon, authenticated', sequence_name);
    end if;
end;
$$;

revoke all on public.math_requests, public.document_contributions from public, anon, authenticated;
grant insert on public.math_requests, public.document_contributions to anon;
grant select, insert, update, delete on public.math_requests, public.document_contributions to authenticated;

create policy "Public can submit material requests" on public.math_requests for insert to anon, authenticated
    with check (status = 'pending' and admin_note is null and reviewed_at is null);
create policy "Admins can manage material requests" on public.math_requests for all to authenticated
    using ((select public.current_user_is_admin())) with check ((select public.current_user_is_admin()));
create policy "Public can submit document contributions" on public.document_contributions for insert to anon, authenticated
    with check (status = 'pending' and admin_note is null and reviewed_at is null);
create policy "Admins can manage document contributions" on public.document_contributions for all to authenticated
    using ((select public.current_user_is_admin())) with check ((select public.current_user_is_admin()));

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('document-submissions','document-submissions',false,15728640,array['application/pdf'])
on conflict (id) do update set public = false, file_size_limit = excluded.file_size_limit, allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "Public can upload PDF contributions" on storage.objects;
drop policy if exists "Admins can view PDF contributions" on storage.objects;
drop policy if exists "Admins can delete PDF contributions" on storage.objects;
create policy "Public can upload PDF contributions" on storage.objects for insert to anon, authenticated
    with check (bucket_id = 'document-submissions' and name ~* '^submissions/[^/]+[.]pdf$');
create policy "Admins can view PDF contributions" on storage.objects for select to authenticated
    using (bucket_id = 'document-submissions' and (select public.current_user_is_admin()));
create policy "Admins can delete PDF contributions" on storage.objects for delete to authenticated
    using (bucket_id = 'document-submissions' and (select public.current_user_is_admin()));

notify pgrst, 'reload schema';
commit;

select
    to_regclass('public.math_requests') as requests_table,
    to_regclass('public.document_contributions') as contributions_table,
    exists(select 1 from information_schema.columns where table_schema='public' and table_name='math_requests' and column_name='reviewed_at') as request_review_ready,
    exists(select 1 from storage.buckets where id='document-submissions' and public=false) as private_pdf_bucket_ready;
