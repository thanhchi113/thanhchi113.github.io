drop policy if exists "Public can upload PDF contributions" on storage.objects;
drop policy if exists "Admins can view PDF contributions" on storage.objects;
drop policy if exists "Admins can delete PDF contributions" on storage.objects;
create policy "Public can upload PDF contributions"
    on storage.objects for insert to anon, authenticated
    with check (
        bucket_id = 'document-submissions'
        and lower(storage.extension(name)) = 'pdf'
    );
create policy "Admins can view PDF contributions"
    on storage.objects for select to authenticated
    using (bucket_id = 'document-submissions' and public.current_user_is_admin());
create policy "Admins can delete PDF contributions"
    on storage.objects for delete to authenticated
    using (bucket_id = 'document-submissions' and public.current_user_is_admin());

drop policy if exists "Admins can upload achievement evidence" on storage.objects;
drop policy if exists "Admins can update achievement evidence" on storage.objects;
drop policy if exists "Admins can delete achievement evidence" on storage.objects;
create policy "Admins can upload achievement evidence"
    on storage.objects for insert to authenticated
    with check (bucket_id = 'achievement-evidence' and public.current_user_is_admin());
create policy "Admins can update achievement evidence"
    on storage.objects for update to authenticated
    using (bucket_id = 'achievement-evidence' and public.current_user_is_admin())
    with check (bucket_id = 'achievement-evidence' and public.current_user_is_admin());
create policy "Admins can delete achievement evidence"
    on storage.objects for delete to authenticated
    using (bucket_id = 'achievement-evidence' and public.current_user_is_admin());
